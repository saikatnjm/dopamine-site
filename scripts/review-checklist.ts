// npm run content:checklist — writes a Markdown checklist of every regional
// form that a person hasn't verified yet, grouped by region, with its sources.
// Output: data/dialects/review/YYYY-MM-DD-dialect-review-checklist.md
// (or stdout with --stdout). Approving = editing the data file by hand.

import { mkdirSync, writeFileSync } from "node:fs";
import { DIALECT_CONTENT } from "@/data/dialects";
import { isPublicForm } from "@/lib/dialects/content";
import type { RegionalForm } from "@/lib/dialects/types";
import { t } from "@/lib/i18n/core";

const { regions, concepts, forms, sources } = DIALECT_CONTENT;
const conceptOf = new Map(concepts.map((c) => [c.id, c]));
const sourceOf = new Map(sources.map((s) => [s.id, s]));
const pending = forms.filter((f) => f.status !== "verified" && f.status !== "rejected");
const today = new Date().toISOString().slice(0, 10);

function block(f: RegionalForm): string {
  const c = conceptOf.get(f.conceptId);
  const src = f.sources.map((id) => {
    const s = sourceOf.get(id);
    return s ? (s.url ? `[${s.title}](${s.url})` : s.title) : id;
  });
  return [
    `- [ ] **${f.form}** = ${c ? `${c.emoji} ${c.standard}` : f.conceptId} — \`${f.id}\` (${f.confidence}, ${f.script}${isPublicForm(f) ? ", **shown on the site as sourced**" : ", hidden"})`,
    f.variants.length ? `  - অন্য বানান: ${f.variants.join(", ")}` : "",
    f.area ? `  - এলাকা: ${f.area}` : "",
    f.example ? `  - উদাহরণ: “${f.example}”` : "",
    `  - সূত্র: ${src.join(" · ")}`,
    f.notes ? `  - নোট: ${f.notes}` : "",
    "  - [ ] বানান ঠিক  - [ ] অর্থ ঠিক  - [ ] এই এলাকায় সত্যিই বলে",
  ]
    .filter(Boolean)
    .join("\n");
}

const out: string[] = [
  `# Dialect review checklist — ${today}`,
  "",
  "Generated by `npm run content:checklist`. Tick what a person who knows the dialect has checked. Then edit the form in `data/dialects/forms/<region>.ts`:",
  "",
  '- correct → `status: "verified"` (fix the spelling first if needed; romanized forms need a Bangla `form` + `script: "bangla"`)',
  '- wrong → `status: "rejected"` and say why in `notes` (keeps it from coming back)',
  "- unsure → leave `needs_review` and add a note",
  "",
  "Then run `npm run validate:content`. Verified forms also become scored quiz questions.",
  "",
  `Pending: ${pending.length} form(s) (${pending.filter(isPublicForm).length} currently shown as "sourced").`,
];

for (const r of regions) {
  const fs = pending.filter((f) => f.regions[0] === r.id);
  if (fs.length === 0) continue;
  out.push("", `## ${t(r.name, "bn")} (${r.id}) — ${fs.length}`, "", ...fs.map(block));
}
if (pending.length === 0) out.push("", "Nothing to review. 🎉");

const text = `${out.join("\n")}\n`;
if (process.argv.includes("--stdout")) {
  process.stdout.write(text);
} else {
  const dir = new URL("../data/dialects/review/", import.meta.url);
  mkdirSync(dir, { recursive: true });
  const file = new URL(`${today}-dialect-review-checklist.md`, dir);
  writeFileSync(file, text);
  console.log(`Wrote ${file.pathname.replace(/^.*\/data\//, "data/")} (${pending.length} forms)`);
}

// npm run content:checklist — writes a Markdown checklist of every dialect
// word and question that is not yet live, for a person to review.
// Output: data/dialects/review/YYYY-MM-DD-dialect-review-checklist.md
// (or stdout with --stdout). Approving = editing the data file by hand.

import { mkdirSync, writeFileSync } from "node:fs";
import { DIALECT_CONTENT } from "@/data/dialects";
import type { DialectWord, QuizQuestion } from "@/lib/dialects/types";
import { t } from "@/lib/i18n/core";

const { districts, words, questions } = DIALECT_CONTENT;
const pendingWords = words.filter((w) => w.verificationStatus !== "verified");
const pendingQuestions = questions.filter((q) => q.status !== "published");
const wordById = new Map(words.map((w) => [w.id, w]));
const today = new Date().toISOString().slice(0, 10);

function wordBlock(w: DialectWord): string {
  return [
    `- [ ] **${w.localWord}** → ${w.standardWord} — \`${w.id}\` (${w.verificationStatus})`,
    `  - অর্থ: ${w.meaningBn}${w.meaningEn ? ` · EN: ${w.meaningEn}` : ""}`,
    `  - জেলা: ${w.districtIds.join(", ")}${w.variants.length ? ` · অন্য বানান: ${w.variants.join(", ")}` : ""}`,
    w.pronunciation ? `  - উচ্চারণ: ${w.pronunciation}` : "",
    w.exampleSentence ? `  - উদাহরণ: “${w.exampleSentence}”` : "  - উদাহরণ: _(নেই — যোগ করলে শব্দের পেজ সার্চে আসবে)_",
    `  - উৎস: ${w.source}${w.contributor ? ` · ${w.contributor}` : ""}`,
    w.notes ? `  - নোট: ${w.notes}` : "",
    "  - [ ] বানান ঠিক  - [ ] অর্থ ঠিক  - [ ] এই জেলায় ব্যবহার হয়",
  ]
    .filter(Boolean)
    .join("\n");
}

function questionBlock(q: QuizQuestion): string {
  const w = wordById.get(q.wordId);
  const options = q.options.map((o) => `${o.id === q.correctOptionId ? "✅" : "▫️"} ${o.text}${o.gloss ? ` (${o.gloss})` : ""}`).join(" · ");
  return [
    `- [ ] \`${q.id}\` (${q.status}, ${q.difficulty}) — word \`${q.wordId}\`${w ? ` ${w.localWord}` : " ⚠️ missing"} [${w?.verificationStatus ?? "?"}]`,
    `  - প্রশ্ন: ${t(q.question, "bn")}`,
    `  - অপশন: ${options}`,
    `  - ব্যাখ্যা: ${t(q.explanation, "bn")}`,
    "  - [ ] একটাই সঠিক উত্তর  - [ ] ভুল অপশনগুলো সত্যিই ভুল  - [ ] ব্যাখ্যা ঠিক",
  ].join("\n");
}

const out: string[] = [
  `# Dialect review checklist — ${today}`,
  "",
  "Generated by `npm run content:checklist`. Tick what a person has checked. To approve:",
  "",
  '1. Word: set `verificationStatus: "verified"` in `data/dialects/words/<district>.ts` (add `exampleSentence` if you can).',
  '2. Question: set `status: "published"` in `data/dialects/questions.ts` — only after its word is verified.',
  "3. Run `npm run validate:content`. Unsure? Leave it as `needs_review` and write why in `notes`.",
  "",
  `Pending: ${pendingWords.length} word(s), ${pendingQuestions.length} question(s).`,
];

for (const d of districts) {
  const ws = pendingWords.filter((w) => w.districtIds[0] === d.id);
  const qs = pendingQuestions.filter((q) => q.districtIds[0] === d.id);
  if (ws.length === 0 && qs.length === 0) continue;
  out.push("", `## ${t(d.name, "bn")} (${d.id})`);
  if (ws.length) out.push("", "### শব্দ", "", ...ws.map(wordBlock));
  if (qs.length) out.push("", "### প্রশ্ন", "", ...qs.map(questionBlock));
}
if (pendingWords.length === 0 && pendingQuestions.length === 0) out.push("", "Nothing to review. 🎉");

const text = `${out.join("\n")}\n`;
if (process.argv.includes("--stdout")) {
  process.stdout.write(text);
} else {
  const dir = new URL("../data/dialects/review/", import.meta.url);
  mkdirSync(dir, { recursive: true });
  const file = new URL(`${today}-dialect-review-checklist.md`, dir);
  writeFileSync(file, text);
  console.log(`Wrote ${file.pathname.replace(/^.*\/data\//, "data/")} (${pendingWords.length} words, ${pendingQuestions.length} questions)`);
}
